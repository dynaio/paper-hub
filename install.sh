#!/usr/bin/env bash
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VENV="${AMAYAS_VENV:-$HOME/Code/.venv}"
LAUNCHER="$HOME/.amayas/amayas"
ICON="$HOME/.amayas/amayas-icon.png"
VAULT="$HOME/Papers"
DESKTOP_DIR="$HOME/.local/share/applications"
DESKTOP_FILE="$DESKTOP_DIR/amayas.desktop"

echo "==> amayas installer"
echo "    repo:  $REPO_DIR"
echo "    venv:  $VENV"

if [ ! -x "$VENV/bin/python" ]; then
    echo "!! venv not found at $VENV"
    echo "   Set AMAYAS_VENV=/path/to/venv and rerun."
    exit 1
fi

"$VENV/bin/python" - <<'PY' || "$VENV/bin/pip" install -r "$REPO_DIR/requirements.txt"
import importlib, sys
missing = []
for mod, name in [("PyQt6", "PyQt6"), ("fitz", "PyMuPDF"), ("PIL", "Pillow")]:
    try:
        importlib.import_module(mod)
    except ImportError:
        missing.append(name)
if missing:
    print("Missing:", " ".join(missing)); sys.exit(2)
print("All dependencies present.")
PY

# icon (copy bundled if no user icon)
mkdir -p "$HOME/.amayas" "$VAULT/files"
if [ -f "$REPO_DIR/logo.png" ] && [ ! -f "$ICON" ]; then
    cp "$REPO_DIR/logo.png" "$ICON"
    echo "==> Installed default icon to $ICON"
fi

# launcher script
cat > "$LAUNCHER" <<LAUNCH
#!/usr/bin/env bash
exec "$VENV/bin/python" "$REPO_DIR/main.py" "\$@"
LAUNCH
chmod +x "$LAUNCHER"

# .desktop entry (will also be regenerated by the app on launch)
mkdir -p "$DESKTOP_DIR"
cat > "$DESKTOP_FILE" <<DESKTOP
[Desktop Entry]
Type=Application
Version=1.0
Name=Amayas
GenericName=Paper Companion
Comment=Research paper vault with hash-locked versions
Exec=$LAUNCHER
Icon=$ICON
Terminal=false
Categories=Office;Education;Utility;
StartupNotify=true
StartupWMClass=amayas
Keywords=papers;research;pdf;documents;vault;
DESKTOP
echo "==> Wrote desktop entry to $DESKTOP_FILE"

if [ -w /usr/local/bin ]; then
    ln -sf "$LAUNCHER" /usr/local/bin/amayas
    echo "==> Linked /usr/local/bin/amayas"
else
    echo "==> Sudo needed for /usr/local/bin/amayas"
    sudo ln -sf "$LAUNCHER" /usr/local/bin/amayas
fi

command -v update-desktop-database >/dev/null 2>&1 && \
    update-desktop-database "$DESKTOP_DIR" >/dev/null 2>&1 || true

echo
echo "Done."
echo "  Vault:  $VAULT/"
echo "  Run:    amayas   (or search Amayas in your app list)"
